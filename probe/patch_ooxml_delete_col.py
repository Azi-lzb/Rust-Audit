    '                let mut cols = columns.clone();\n'
    '                cols.sort_unstable();\n'
    '                cols.dedup();\n'
    '                cols.reverse();\n'
    '                let escaped = sheet_name.replace(\\\'\\\', "''");\n'
    '                for prefix in [\n'
    '                    format!("\'{}\'!", escaped),\n'
    '                    format!("{}!", escaped),\n'
    '                ] {\n'
    '                    let pattern = format!(\n'
    '                        r#"({})((?:\\$?[A-Za-z]+\\$?\\d+(?::\\$?[A-Za-z]+\\$?\\d+)?))"#,\n'
    '                        regex::escape(&prefix),\n'
    '                    );\n'
    '                    if let Ok(re) = regex::Regex::new(&pattern) {\n'
    '                        rebuilt = re\n'
    '                            .replace_all(&rebuilt, |caps: &regex::Captures| {\n'
    '                                match shift_single_range(&caps[2], cols[0]) {\n'
    '                                    Some(new_area) => {\n'
    '                                        changed = true;\n'
    '                                        format!("{}{}", &caps[1], new_area)\n'
    '                                    }\n'
    '                                    None => caps[0].to_owned(),\n'
    '                                }\n'
    '                            })\n'
    '                            .into_owned();\n'
    '                    }\n'
    '                }\n'
    '            }\n'
    '            if changed {\n'
    '                format!("{}{}{}", &caps[1], rebuilt, &caps[3])\n'
    '            } else {\n'
    '                caps[0].to_owned()\n'
    '            }\n'
    '        })\n'
    '        .into_owned()\n'
    '}\n'
