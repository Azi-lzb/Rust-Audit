    '                token.3\n'
    '            );\n'
    '            let new = format!(\n'
    '                "{}{}{}{}",\n'
    '                if token.0 { "$" } else { "" },\n'
    '                column_letters_of(token.1 - 1),\n'
    '                if token.2 { "$" } else { "" },\n'
    '                token.3\n'
    '            );\n'
    '            rebuilt = rebuilt.replacen(&old, &new, 1);\n'
    '        }\n'
    '        return Some(rebuilt);\n'
    '    }\n'
    '    let new_min = if c1 == deleted { c1 + 1 } else { c1 };\n'
    '    let new_max = c2 - 1;\n'
    '    if new_max < new_min {\n'
    '        return None;\n'
    '    }\n'
    '    let mut rebuilt = range.to_owned();\n'
    '    for token in &tokens {\n'
    '        let old = format!(\n'
    '            "{}{}{}{}",\n'
    '            if token.0 { "$" } else { "" },\n'
    '            column_letters_of(token.1),\n'
    '            if token.2 { "$" } else { "" },\n'
    '            token.3\n'
    '        );\n'
    '        let new_column = if token.1 < deleted {\n'
    '            token.1\n'
    '        } else if token.1 == deleted {\n'
