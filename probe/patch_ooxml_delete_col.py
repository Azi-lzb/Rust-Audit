    '/// 删除单个列：行内单元格移除/左移，dimension/mergeCells/sqref 区域调整。\n'
    'fn delete_single_column(sheet_xml: &str, deleted: u32) -> String {\n'
    '    let shift = |column: u32| -> u32 {\n'
    '        if column > deleted {\n'
    '            column - 1\n'
