    '        } else {\n'
    '            token.1 - 1\n'
    '        };\n'
    '        let new = format!(\n'
    '            "{}{}{}{}",\n'
    '            if token.0 { "$" } else { "" },\n'
    '            column_letters_of(new_column),\n'
    '            if token.2 { "$" } else { "" },\n'
    '            token.3\n'
    '        );\n'
    '        rebuilt = rebuilt.replacen(&old, &new, 1);\n'
    '    }\n'
    '    Some(rebuilt)\n'
