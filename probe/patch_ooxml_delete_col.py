    'fn shift_range_list(list: &str, deleted: u32) -> Option<String> {\n'
    '    let areas: Vec<Option<String>> = list\n'
    '        .split(\' \')\n'
    '        .map(|area| shift_single_range(area, deleted))\n'
    '        .collect();\n'
    '    if areas.iter().all(Option::is_none) {\n'
