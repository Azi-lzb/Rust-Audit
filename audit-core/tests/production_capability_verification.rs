/// S1-F01 审核副本的共享读回断言：Umya 证据段使用。
fn assert_s1_audit_copy_dump(dump: &excel_reader::WorkbookDump) -> Result<()> {
    for (cell, expected) in [
        ("A1", "代码"),
        ("B1", "名称"),
        ("A2", "I001"),
        ("B2", "测试机构"),
    ] {
        let actual = value_text(dump, "外部维表", cell);
        anyhow::ensure!(
            actual == expected,
            "外部维表!{cell} expected {expected:?}, observed {actual:?}"
        );
    }
    for (cell, expected) in [("A1", "B2+1"), ("B2", "A1*10")] {
        let actual = cell_formula(dump, "检查表", cell);
        anyhow::ensure!(
            actual == expected,
            "检查表!{cell} formula expected {expected:?}, observed {actual:?}"
        );
    }
    let comments = dump
        .sheets
        .iter()
        .find(|sheet| sheet.name == "检查表")
        .context("检查表 missing")?
        .comments
        .clone();
    anyhow::ensure!(
        comments.get("A1").map(String::as_str) == Some("模板口径说明"),
        "template comment expected at A1, observed {comments:?}"
    );
    Ok(())
}
