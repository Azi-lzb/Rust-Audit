//! Production capability verification for the Excel-Core edit route.
//!
//! This harness runs the exact S1-F01 formula-copy batch, the S3-F03
//! explanation write-back batch and the S3-F05 financial-form edit batch
//! through the full `ExcelModifier` path with the production capability
//! record from `audit_core::excel_route`. Every preservation contract that
//! the production capability declares is exercised on synthetic workbooks and
//! asserted by independent read-back (excel_reader dumps, OOXML package
//! inspection and umya reopen). The runs also prove the original inputs stay
//! byte-identical.
//!
//! Running the test alone verifies the capability. Setting
//! `AUDIT_CAPABILITY_REPORT=<path>` additionally writes the JSON evidence
//! report referenced by the committed capability registration; only a fully
//! passing run writes the report.

use anyhow::{Context, Result};
use excel_editor::{
    inspect_xlsx_profile, CellValue, EditOperation, EditOperationKind, ExcelEditPlan,
    ExcelModifier, OpenpyxlWorkerConfig, OpenpyxlXlsxBackend, OpenpyxlXlsxValidator,
    OutputValidator, PreservationRequirement, RangeStyleMode, SheetVisibility, WorkbookFeature,
    WorkbookFormat,
};
use excel_reader::read_workbook;
use excel_route_support::*;
use serde_json::{json, Value};
use std::{
    collections::BTreeMap,
    fs,
    path::{Path, PathBuf},
    process::Command,
    sync::{Arc, Mutex},
    time::{SystemTime, UNIX_EPOCH},
};

mod excel_route_support {
    use super::*;

    #[derive(serde::Serialize)]
    pub struct VerificationStep {
        pub name: &'static str,
        pub detail: String,
    }

    impl VerificationStep {
        pub fn new(name: &'static str, detail: impl Into<String>) -> Self {
            Self {
                name,
                detail: detail.into(),
            }
        }
    }

    #[derive(serde::Serialize)]
    pub struct SampleVerification {
        pub sample_id: String,
        pub batch: &'static str,
        pub steps: Vec<VerificationStep>,
    }

    pub struct TestDir(PathBuf);

    impl TestDir {
        pub fn new(label: &str) -> Self {
            let nonce = SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .expect("system clock after Unix epoch")
                .as_nanos();
            let path = std::env::temp_dir().join(format!(
                "audit_capability_verification_{label}_{}_{}",
                std::process::id(),
                nonce
            ));
            fs::create_dir_all(&path).expect("create verification directory");
            Self(path)
        }

        pub fn path(&self, name: &str) -> PathBuf {
            self.0.join(name)
        }
    }

    impl Drop for TestDir {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.0);
        }
    }

    /// Runs `action` and returns its step record; a failure aborts the test.
    pub fn record(step_name: &'static str, action: impl FnOnce() -> Result<String>) -> VerificationStep {
        match action() {
            Ok(detail) => VerificationStep::new(step_name, detail),
            Err(error) => panic!("verification step {step_name} failed: {error:#}"),
        }
    }

    pub fn sha256_file(path: &Path) -> Result<String> {
        use sha2::{Digest, Sha256};
        let bytes = fs::read(path).with_context(|| format!("read {}", path.display()))?;
        Ok(format!("{:x}", Sha256::digest(&bytes)))
    }

    /// Compares the zip part name sets of two workbooks and reports parts that
    /// disappeared from the edited output. calcChain is regenerated by every
    /// full-rewrite engine and may legitimately disappear.
    pub fn disappeared_parts(original: &Path, output: &Path) -> Result<Vec<String>> {
        let names = |path: &Path| -> Result<std::collections::BTreeSet<String>> {
            let file = fs::File::open(path)?;
            let mut archive = zip::ZipArchive::new(file)?;
            let mut names = std::collections::BTreeSet::new();
            for index in 0..archive.len() {
                let entry = archive.by_index(index)?;
                if !entry.is_dir() {
                    names.insert(entry.name().to_owned());
                }
            }
            Ok(names)
        };
        let before = names(original)?;
        let after = names(output)?;
        Ok(before
            .difference(&after)
            .filter(|name| name.to_ascii_lowercase() != "xl/calcchain.xml")
            .cloned()
            .collect())
    }

    pub fn cell_text(dump: &excel_reader::WorkbookDump, sheet: &str, cell: &str) -> String {
        dump.sheets
            .iter()
            .find(|candidate| candidate.name == sheet)
            .unwrap_or_else(|| panic!("sheet {sheet} missing from dump"))
            .values
            .get(cell)
            .map(|value| match &value["value"] {
                serde_json::Value::String(text) => text.clone(),
                serde_json::Value::Number(number) => number.to_string(),
                other => other.to_string(),
            })
            .unwrap_or_default()
    }

    pub fn cell_formula(dump: &excel_reader::WorkbookDump, sheet: &str, cell: &str) -> String {
        dump.sheets
            .iter()
            .find(|candidate| candidate.name == sheet)
            .unwrap_or_else(|| panic!("sheet {sheet} missing from dump"))
            .formulas
            .get(cell)
            .cloned()
            .unwrap_or_default()
    }

    pub fn sheet_names(dump: &excel_reader::WorkbookDump) -> Vec<String> {
        dump.sheets.iter().map(|sheet| sheet.name.clone()).collect()
    }

    pub fn assert_eq_step(
        left: impl Into<Value>,
        right: impl Into<Value>,
    ) -> impl FnOnce() -> Result<String> {
        let left = left.into();
        let right = right.into();
        move || {
            anyhow::ensure!(
                left == right,
                "readback mismatch: expected {right}, observed {left}"
            );
            Ok(format!("{left}"))
        }
    }
}

fn value_text(dump: &excel_reader::WorkbookDump, sheet: &str, cell: &str) -> String {
    cell_text(dump, sheet, cell)
}

/// The production modifier under verification. Panics on platforms without
/// committed evidence so the harness can never silently verify nothing.
fn production_modifier() -> (ExcelModifier, excel_editor::BackendCapability) {
    let (modifier, capability) = audit_core::excel_route::production_modifier(
        "production-capability-verification",
    )
    .expect("build production modifier");
    let capability = capability.expect(
        "production capability must be registered on the evidence platform; \
         run this harness on a registered evidence platform",
    );
    (modifier, capability)
}

/// Asserts every declared feature is present in the workbook profile so the
/// sample really exercises the declared scope.
fn require_features(profile: &excel_editor::WorkbookProfile, expected: &[WorkbookFeature]) {
    for feature in expected {
        assert!(
            profile.features_present.contains(feature),
            "synthetic sample must contain declared feature {feature:?}"
        );
    }
}

#[test]
fn verifies_the_production_route_on_the_declared_capability() -> Result<()> {
    let platform = audit_core::excel_route::runtime_platform();
    let capability = audit_core::excel_route::production_capability(&platform)
        .expect("production capability must be registered on the current platform");
    let evidence = capability
        .evidence
        .as_ref()
        .expect("registered platform must identify its evidence report");
    assert_eq!(capability.platform, platform);

    let mut samples = Vec::new();
    samples.push(verify_s3_f5_form_edit_batch().context("S3-F05 form edit batch")?);
    samples.push(verify_s1_f1_formula_copy_batch().context("S1-F01 formula copy batch")?);
    samples.push(verify_s3_f03_explanation_writeback().context("S3-F03 explanation write-back")?);

    // Write the evidence report only for a fully passing run.
    if let Some(report_path) = std::env::var_os("AUDIT_CAPABILITY_REPORT").map(PathBuf::from) {
        let report = json!({
            "schema_version": 1,
            "sample_set_id": evidence.sample_id,
            "platform": platform,
            "engine": evidence.engine_version,
            "adapter": evidence.adapter_version,
            "verified_at": chrono::Local::now().format("%Y-%m-%d %H:%M:%S %Z").to_string(),
            "harness": "audit-core/tests/production_capability_verification.rs",
            "capabilities": {
                "operations": audit_core::excel_route::PRODUCTION_OPERATIONS
                    .iter()
                    .map(|operation| format!("{operation:?}"))
                    .collect::<Vec<_>>(),
                "supported_features": production_supported_feature_names(),
                "preserved": preserved_requirement_names(),
            },
            "samples": samples,
        });
        if let Some(parent) = report_path.parent() {
            fs::create_dir_all(parent)
                .with_context(|| format!("create {}", parent.display()))?;
        }
        fs::write(&report_path, serde_json::to_vec_pretty(&report)?)
            .with_context(|| format!("write {}", report_path.display()))?;
        println!("capability evidence report written to {}", report_path.display());
    }
    Ok(())
}

