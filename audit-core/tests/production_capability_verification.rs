fn build_s1_f1_target(path: &Path) -> Result<()> {
    use umya_spreadsheet::structs::{
        ConditionalFormatValues, ConditionalFormatting, ConditionalFormattingOperatorValues,
        ConditionalFormattingRule, Formula, OddHeader, SequenceOfReferences,
    };
    let mut workbook = umya_spreadsheet::new_file();
    let sheet = workbook.sheet_by_name_mut("Sheet1")?;
    sheet.set_name("检查表");
    sheet.cell_mut("A1").set_value_string("机构存量");
    sheet.cell_mut("A2").set_value_number(21.5);
    sheet.cell_mut("A3").set_formula("A2*2");
    sheet.cell_mut("C1").set_value_string("说明列");
    sheet.add_merge_cells("C2:D2");

    let mut rule = ConditionalFormattingRule::default();
    rule.set_type(ConditionalFormatValues::CellIs);
    rule.set_operator(ConditionalFormattingOperatorValues::LessThan);
    rule.set_priority(1);
    rule.set_formula(Formula::default().set_string_value("0").clone());
    let mut formatting = ConditionalFormatting::default();
    formatting.set_sequence_of_references(SequenceOfReferences::default().set_sqref("A1:B2").clone());
    formatting.add_conditional_collection(rule);
    sheet.add_conditional_formatting_collection(formatting);

    use umya_spreadsheet::structs::{
        DataValidation, DataValidationOperatorValues, DataValidationValues, DataValidations,
    };
    let mut validation = DataValidation::default();
    validation.set_type(DataValidationValues::Decimal);
    validation.set_operator(DataValidationOperatorValues::GreaterThanOrEqual);
    validation.set_sequence_of_references(SequenceOfReferences::default().set_sqref("A1:A5").clone());
    validation.set_formula1("0");
    let mut validations = DataValidations::default();
    validations.add_data_validation_list(validation);
    sheet.set_data_validations(validations);

    sheet.header_footer_mut().set_odd_header(OddHeader::default().set_value("报送页眉").clone());
    let mut pane = umya_spreadsheet::structs::Pane::default();
    pane.set_horizontal_split(1.0);
    let mut coordinate = umya_spreadsheet::structs::Coordinate::default();
    coordinate.set_coordinate("A2");
    pane.set_top_left_cell(coordinate);
    pane.set_active_pane(umya_spreadsheet::structs::PaneValues::BottomLeft);
    pane.set_state(umya_spreadsheet::structs::PaneStateValues::Frozen);
    let views = sheet.sheet_views_mut();
    if let Some(view) = views.sheet_view_list_mut().first_mut() {
        view.set_pane(pane);
    } else {
        let mut view = umya_spreadsheet::structs::SheetView::default();
        view.set_pane(pane);
        views.add_sheet_view_list_mut(view);
    }

    let mut comment = umya_spreadsheet::Comment::default();
    comment.new_comment("C1");
    comment.set_author("填报人");
    comment.set_text_string("源文件说明");
    sheet.add_comments(comment);

    let mut name = umya_spreadsheet::DefinedName::default();
    name.set_name("指标区域").set_address("'检查表'!$A$1:$B$2");
    workbook.add_defined_names(name);

    umya_spreadsheet::writer::xlsx::write(&workbook, path)
        .with_context(|| format!("save target {}", path.display()))?;
    Ok(())
}

